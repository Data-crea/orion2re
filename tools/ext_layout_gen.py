#!/usr/bin/env python3
"""Generate src/ext/ext_layout_table.inc from the game's own header.

    python tools/ext_layout_gen.py           # write the table
    python tools/ext_layout_gen.py --check   # exit 1 if it is out of date

The Extension API sends the game's records as raw bytes (`STATE_SNAPSHOT`
and some blocks). The LAYOUT message (docs/extension-api.md) tells a client
where every member of those records is: its name, offset and size, as the
compiler laid it out. This script writes the list of members; the offsets
and sizes are filled in by the compiler (`offsetof`, `sizeof`), so a record
that grows or moves needs nothing here. A member that is removed or renamed
stops the build at its line in the table: run this script again.

The records are the ones the snapshot and the blocks copy whole (ROOTS)
and every record type they contain. Python 3 only, no dependencies.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(HERE, "src", "game", "orion2.h")
OUT = os.path.join(HERE, "src", "ext", "ext_layout_table.inc")

#: The records the wire carries as raw bytes, in the snapshot's order, then
#: the blocks' (CMBT's units, CMSL's missiles, FMOV's move info).
ROOTS = ("s_settings", "s_player", "s_star_data", "s_ship_data", "s_colony",
         "s_planet_data", "s_nebula", "s_leader_data", "s_antaran",
         "s_ship_icon", "s_combat_data", "s_missile", "s_ship_move_info")

MEMBER = re.compile(r"^(struct\s+)?([\w:]+)\s*(\*?)\s*(\w+)((?:\[[^\]]+\])*);$")


def records(text):
    """{name: [(member type, member name, is_pointer)]} of every struct."""
    out = {}
    for m in re.finditer(r"^struct (\w+) \{\n(.*?)^\};", text, re.S | re.M):
        members = []
        for line in m.group(2).splitlines():
            line = line.split("//")[0].strip()
            if not line or line.startswith("#"):
                continue
            mm = MEMBER.match(line)
            # a struct the wire does not carry may hold what this reader
            # does not know (a union); only one in the closure must not
            members.append((mm.group(2), mm.group(4), bool(mm.group(3)))
                           if mm else ("?", line, False))
        out[m.group(1)] = members
    return out


def closure(recs):
    """ROOTS and every record type they contain, roots first."""
    order, todo = [], list(ROOTS)
    while todo:
        name = todo.pop(0)
        if name in order:
            continue
        if name not in recs:
            raise SystemExit(f"{name} is not a struct in {HEADER}")
        order.append(name)
        for typ, _member, ptr in recs[name]:
            if typ == "?":
                raise SystemExit(f"{name}: cannot read member {_member!r}")
            if not ptr and typ in recs and typ not in order:
                todo.append(typ)
    return order


def render(text):
    recs = records(text)
    order = closure(recs)
    lines = ["// GENERATED by tools/ext_layout_gen.py from src/game/orion2.h.",
             "// Do not edit: run the script again. Offsets and sizes are the",
             "// compiler's (offsetof, sizeof); this file lists the members.",
             ""]
    for name in order:
        lines.append(f"LAYOUT_RECORD_BEGIN({name})")
        for typ, member, ptr in recs[name]:
            rec = f'"{typ}"' if not ptr and typ in recs else "nullptr"
            lines.append(f"    LAYOUT_FIELD({name}, {member}, {rec})")
        lines.append(f"LAYOUT_RECORD_END({name})")
        lines.append("")
    lines.append("#define LAYOUT_RECORDS \\")
    lines += [f"    LAYOUT_RECORD({name}) \\" for name in order]
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(open(HEADER, encoding="utf-8").read())
    if "--check" in argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print(f"{OUT}: {'up to date' if same else 'OUT OF DATE'}")
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{OUT}: written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
